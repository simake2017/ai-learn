/* =============================================================================
 * test_02_matmul.c - 矩阵乘法单元测试
 *
 * 📚 学习目标：
 *   理解 matmul_forward 如何实现 y = x @ W^T + b
 *   这是 Transformer 中最核心的运算——QKV 投影、MLP、LM Head 全靠它
 *
 * 🧮 数学原理：
 *   y[b, t, o] = Σ_i x[b, t, i] * W[o, i] + bias[o]
 *
 *   等价于矩阵形式: Y = X · W^T + b
 *   - X: (B*T, C)     输入，B个句子，每句T个词，每词C维
 *   - W: (OC, C)      权重矩阵，OC 个输出特征，每个特征一个 C 维"检测器"
 *   - Y: (B*T, OC)    输出
 *
 * 💡 直觉：
 *   W 的每一行是一个"特征检测器"。
 *   x 和 W 的第 o 行做点积 → 输出第 o 个特征值。
 *   点积大 = 输入和这个检测器相似 → 该特征被"激活"
 *
 * 🔍 测试策略：
 *   1. 用 2×3 输入 × 4×3 权重 → 2×4 输出，手算验证
 *   2. 测试有无 bias 的情况
 * =============================================================================
 */

#include "test_utils.h"
#include "../c/transformer.h"

int main() {
    TEST_BEGIN("矩阵乘法 y = x @ W^T + b");

    /* ──────────────────────────────────────────────
     * 测试 1: 基础矩阵乘法 (B=1, T=2, C=3, OC=4)
     *
     * X = | 1  2  3 |     W = | 1  0  0 |    b = [1, 1, 1, 1]
     *     | 4  5  6 |         | 0  1  0 |
     *                         | 0  0  1 |
     *                         | 1  1  1 |
     *
     * Y = X @ W^T + b
     *   = | 1*1+2*0+3*0+1   1*0+2*1+3*0+1   1*0+2*0+3*1+1   1+2+3+1 |
     *     | 4*1+5*0+6*0+1   4*0+5*1+6*0+1   4*0+5*0+6*1+1   4+5+6+1 |
     *   = | 2  3  4  7 |
     *     | 5  6  7  16|
     * ────────────────────────────────────────────── */

    printf("--- 测试 1: 2×3 输入, 4×3 权重 ---\n\n");

    // 这里相当于 b t 融合，一个句子，2个token ,3个向量
    float x1[] = {1, 2, 3, // 这里就是矩阵融合了
                  4, 5, 6};

    float w1[] = {1, 0, 0,     /* 检测第 1 个特征 */
                  0, 1, 0,     /* 检测第 2 个特征 */
                  0, 0, 1,     /* 检测第 3 个特征 */
                  1, 1, 1};    /* 检测所有特征之和 */

    float b1[] = {1, 1, 1, 1};
    float out1[8];  /* 2×4 */

    print_mat("X", x1, 2, 3);
    print_mat("W", w1, 4, 3);
    print_vec("b", b1, 4);
    print_sep();

    matmul_forward(out1, x1, w1, b1, 1, 2, 3, 4);

    print_mat("Y = X @ W^T + b", out1, 2, 4);
    print_sep();

    /* 第 1 行: [1,2,3] @ W^T + [1,1,1,1] */
    printf("第 1 行手算: [1,2,3] @ W^T + b = [2, 3, 4, 7]\n");
    ASSERT_CLOSE(out1[0], 2.0f,  1e-5, "Y[0][0] = 1+0+0+1");
    ASSERT_CLOSE(out1[1], 3.0f,  1e-5, "Y[0][1] = 0+2+0+1");
    ASSERT_CLOSE(out1[2], 4.0f,  1e-5, "Y[0][2] = 0+0+3+1");
    ASSERT_CLOSE(out1[3], 7.0f,  1e-5, "Y[0][3] = 1+2+3+1");
    print_sep();

    /* 第 2 行: [4,5,6] @ W^T + [1,1,1,1] */
    printf("第 2 行手算: [4,5,6] @ W^T + b = [5, 6, 7, 16]\n");
    ASSERT_CLOSE(out1[4], 5.0f,  1e-5, "Y[1][0] = 4+0+0+1");
    ASSERT_CLOSE(out1[5], 6.0f,  1e-5, "Y[1][1] = 0+5+0+1");
    ASSERT_CLOSE(out1[6], 7.0f,  1e-5, "Y[1][2] = 0+0+6+1");
    ASSERT_CLOSE(out1[7], 16.0f, 1e-5, "Y[1][3] = 4+5+6+1");

    /* ──────────────────────────────────────────────
     * 测试 2: 无 bias (bias = NULL)
     *
     * 同样的 X 和 W，但 b = NULL → 不加偏置
     * Y = X @ W^T = | 1  2  3  6 |
     *               | 4  5  6  15|
     * ────────────────────────────────────────────── */

    print_sep();
    printf("--- 测试 2: 无 bias ---\n\n");

    float out2[8];
    matmul_forward(out2, x1, w1, NULL, 1, 2, 3, 4);

    printf("无 bias: Y[0] = [1, 2, 3, 6], Y[1] = [4, 5, 6, 15]\n");
    ASSERT_CLOSE(out2[0], 1.0f,  1e-5, "Y_noBias[0][0]");
    ASSERT_CLOSE(out2[3], 6.0f,  1e-5, "Y_noBias[0][3]");
    ASSERT_CLOSE(out2[7], 15.0f, 1e-5, "Y_noBias[1][3]");

    /* ──────────────────────────────────────────────
     * 测试 3: B=2, T=1（批量维度）
     *
     * 验证 batch 维度正确展开
     * ────────────────────────────────────────────── */

    print_sep();
    printf("--- 测试 3: B=2, T=1 批量测试 ---\n\n");

    // 这个方法相当于 b t 融合，一共2个句子，每个句子一个token,一个token 三个向量
    float x3[] = {1, 2, 3,    /* batch 0 */
                  4, 5, 6};   /* batch 1 */
    float w3[] = {1, 1, 1};   /* 1 个输出特征 */
    float b3[] = {0};
    float out3[2];

    matmul_forward(out3, x3, w3, b3, 2, 1, 3, 1);

    printf("B=2: batch0 = 1+2+3 = 6, batch1 = 4+5+6 = 15\n");
    ASSERT_CLOSE(out3[0], 6.0f,  1e-5, "batch 0");
    ASSERT_CLOSE(out3[1], 15.0f, 1e-5, "batch 1");

    TEST_END();
}
